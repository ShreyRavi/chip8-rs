pub const RAM_SIZE: usize = 4096;
pub const ROM_START: usize = 0x200;

// Standard CHIP-8 font sprites (5 bytes each, 16 chars)
pub const FONT_DATA: [u8; 80] = [
    0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
    0x20, 0x60, 0x20, 0x20, 0x70, // 1
    0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
    0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
    0x90, 0x90, 0xF0, 0x10, 0x10, // 4
    0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
    0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
    0xF0, 0x10, 0x20, 0x40, 0x40, // 7
    0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
    0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
    0xF0, 0x90, 0xF0, 0x90, 0x90, // A
    0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
    0xF0, 0x80, 0x80, 0x80, 0xF0, // C
    0xE0, 0x90, 0x90, 0x90, 0xE0, // D
    0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
    0xF0, 0x80, 0xF0, 0x80, 0x80, // F
];

// SCHIP large font sprites (10 bytes each, digits 0-9)
pub const LARGE_FONT_DATA: [u8; 100] = [
    0xFF, 0xFF, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0xFF, // 0
    0x18, 0x78, 0x78, 0x18, 0x18, 0x18, 0x18, 0x18, 0xFF, 0xFF, // 1
    0xFF, 0xFF, 0x03, 0x03, 0xFF, 0xFF, 0xC0, 0xC0, 0xFF, 0xFF, // 2
    0xFF, 0xFF, 0x03, 0x03, 0xFF, 0xFF, 0x03, 0x03, 0xFF, 0xFF, // 3
    0xC3, 0xC3, 0xC3, 0xC3, 0xFF, 0xFF, 0x03, 0x03, 0x03, 0x03, // 4
    0xFF, 0xFF, 0xC0, 0xC0, 0xFF, 0xFF, 0x03, 0x03, 0xFF, 0xFF, // 5
    0xFF, 0xFF, 0xC0, 0xC0, 0xFF, 0xFF, 0xC3, 0xC3, 0xFF, 0xFF, // 6
    0xFF, 0xFF, 0x03, 0x03, 0x06, 0x0C, 0x18, 0x18, 0x18, 0x18, // 7
    0xFF, 0xFF, 0xC3, 0xC3, 0xFF, 0xFF, 0xC3, 0xC3, 0xFF, 0xFF, // 8
    0xFF, 0xFF, 0xC3, 0xC3, 0xFF, 0xFF, 0x03, 0x03, 0xFF, 0xFF, // 9
];

pub const FONT_ADDR: usize = 0x000;
pub const LARGE_FONT_ADDR: usize = 0x050;

pub struct Memory {
    pub ram: [u8; RAM_SIZE],
}

impl Memory {
    pub fn new() -> Self {
        let mut mem = Memory { ram: [0u8; RAM_SIZE] };
        mem.ram[FONT_ADDR..FONT_ADDR + FONT_DATA.len()].copy_from_slice(&FONT_DATA);
        mem.ram[LARGE_FONT_ADDR..LARGE_FONT_ADDR + LARGE_FONT_DATA.len()]
            .copy_from_slice(&LARGE_FONT_DATA);
        mem
    }

    pub fn load_rom(&mut self, data: &[u8]) {
        let end = ROM_START + data.len();
        assert!(end <= RAM_SIZE, "ROM too large: {} bytes (max {})", data.len(), RAM_SIZE - ROM_START);
        self.ram[ROM_START..end].copy_from_slice(data);
    }

    pub fn read_byte(&self, addr: u16) -> u8 {
        self.ram[addr as usize]
    }

    pub fn write_byte(&mut self, addr: u16, val: u8) {
        self.ram[addr as usize] = val;
    }

    pub fn read_word(&self, addr: u16) -> u16 {
        let hi = self.ram[addr as usize] as u16;
        let lo = self.ram[(addr + 1) as usize] as u16;
        (hi << 8) | lo
    }

    pub fn font_addr(digit: u8) -> u16 {
        FONT_ADDR as u16 + (digit as u16) * 5
    }

    pub fn large_font_addr(digit: u8) -> u16 {
        LARGE_FONT_ADDR as u16 + (digit as u16) * 10
    }
}

impl Default for Memory {
    fn default() -> Self {
        Self::new()
    }
}
